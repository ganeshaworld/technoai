import os
import csv
from pathlib import Path
from datetime import datetime, timezone
from typing import Dict, Any, Optional
from docx import Document as DocxDocument
from docx.shared import Inches, Pt, RGBColor
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from openpyxl import Workbook
from pptx import Presentation
from pptx.util import Inches as PptxInches, Pt as PptxPt
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.config import settings
from backend.app.db.models import Document

class DocumentService:
    @staticmethod
    async def create_document(
        db: AsyncSession,
        user_id: str,
        title: str,
        doc_type: str,
        content: str,
        source_prompt: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None
    ) -> Document:
        doc_type = doc_type.lower()
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_title = "".join(c for c in title if c.isalnum() or c in (" ", "_", "-")).rstrip().replace(" ", "_")
        filename = f"{safe_title}_{timestamp}.{doc_type}"
        file_path = settings.DOCS_DIR / filename

        # Generate actual file binary
        if doc_type == "docx":
            DocumentService._build_docx(file_path, title, content)
        elif doc_type == "pdf":
            DocumentService._build_pdf(file_path, title, content)
        elif doc_type in ("xlsx", "xls"):
            DocumentService._build_xlsx(file_path, title, content)
        elif doc_type == "pptx":
            DocumentService._build_pptx(file_path, title, content)
        elif doc_type == "csv":
            DocumentService._build_csv(file_path, content)
        else:
            # Default to text/markdown
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(f"# {title}\n\n{content}")

        file_size = os.path.getsize(file_path)

        doc = Document(
            user_id=user_id,
            title=title,
            doc_type=doc_type,
            file_path=str(file_path),
            file_size_bytes=file_size,
            source_prompt=source_prompt,
            status="ready",
            metadata_info=metadata or {}
        )
        db.add(doc)
        await db.commit()
        await db.refresh(doc)
        return doc

    @staticmethod
    def _build_docx(path: Path, title: str, content: str):
        doc = DocxDocument()
        heading = doc.add_heading(title, 0)
        heading.runs[0].font.color.rgb = RGBColor(15, 23, 42) # Executive navy
        
        doc.add_paragraph(f"Generated by Technopie AI Assistant | {datetime.now().strftime('%B %d, %Y')}")
        doc.add_paragraph("―" * 40)

        for paragraph in content.split("\n\n"):
            if paragraph.startswith("### "):
                doc.add_heading(paragraph[4:], level=2)
            elif paragraph.startswith("## "):
                doc.add_heading(paragraph[3:], level=1)
            elif paragraph.startswith("- "):
                for item in paragraph.split("\n"):
                    doc.add_paragraph(item.lstrip("- ").strip(), style="List Bullet")
            else:
                doc.add_paragraph(paragraph)
        doc.save(str(path))

    @staticmethod
    def _build_pdf(path: Path, title: str, content: str):
        c = canvas.Canvas(str(path), pagesize=letter)
        width, height = letter
        
        # Header
        c.setFillColorRGB(0.04, 0.07, 0.13) # Navy
        c.setFont("Helvetica-Bold", 18)
        c.drawString(50, height - 50, title[:50])
        
        c.setFillColorRGB(0.3, 0.4, 0.5)
        c.setFont("Helvetica", 9)
        c.drawString(50, height - 68, f"Technopie AI Executive Document | {datetime.now().strftime('%Y-%m-%d')}")
        c.line(50, height - 76, width - 50, height - 76)

        c.setFillColorRGB(0.1, 0.1, 0.1)
        c.setFont("Helvetica", 10)
        y = height - 100
        for line in content.split("\n"):
            if y < 60:
                c.showPage()
                y = height - 50
                c.setFont("Helvetica", 10)
            c.drawString(50, y, line[:90])
            y -= 14

        c.save()

    @staticmethod
    def _build_xlsx(path: Path, title: str, content: str):
        wb = Workbook()
        ws = wb.active
        ws.title = "Executive Summary"
        ws.append([title])
        ws.append(["Generated by Technopie AI", datetime.now().strftime("%Y-%m-%d %H:%M")])
        ws.append([]) # empty row
        
        # Parse lines as rows
        for line in content.split("\n"):
            if line.strip():
                if "," in line:
                    ws.append([cell.strip() for cell in line.split(",")])
                elif "\t" in line:
                    ws.append([cell.strip() for cell in line.split("\t")])
                else:
                    ws.append([line])
        wb.save(str(path))

    @staticmethod
    def _build_pptx(path: Path, title: str, content: str):
        prs = Presentation()
        # Slide 1: Title slide
        title_slide_layout = prs.slide_layouts[0]
        slide = prs.slides.add_slide(title_slide_layout)
        title_shape = slide.shapes.title
        subtitle_shape = slide.placeholders[1]
        title_shape.text = title
        subtitle_shape.text = f"Prepared by Technopie AI Assistant\n{datetime.now().strftime('%B %Y')}"

        # Slide 2: Key Content
        bullet_slide_layout = prs.slide_layouts[1]
        slide2 = prs.slides.add_slide(bullet_slide_layout)
        slide2.shapes.title.text = "Executive Brief"
        body_shape = slide2.shapes.placeholders[1]
        tf = body_shape.text_frame
        
        lines = [line.strip("- ") for line in content.split("\n") if line.strip()][:6]
        for i, line in enumerate(lines):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.text = line
            p.level = 0
            
        prs.save(str(path))

    @staticmethod
    def _build_csv(path: Path, content: str):
        with open(path, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            for line in content.split("\n"):
                if line.strip():
                    if "," in line:
                        writer.writerow([cell.strip() for cell in line.split(",")])
                    else:
                        writer.writerow([line])
